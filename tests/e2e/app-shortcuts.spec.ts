import { readFile } from 'node:fs/promises';
import { test, expect } from '../support/browser-test';
import { showSidebar, closeSidebar } from '../support/settings-navigation';
import { openDocumentNote } from '../support/document-editor';
import { showSource } from '../support/editor-navigation';

test('pins apps without opening them, retains shortcuts after reload and removes them', async ({ page, context }) => {
  await context.addCookies(JSON.parse(await readFile('.local/e2e-cookies.json', 'utf8')));
  await page.goto('/?view=apps');
  await page.getByRole('button', { name: '将博客加入左侧菜单', exact: true }).click();
  await page.getByRole('button', { name: '将To Doo加入左侧菜单', exact: true }).click();
  await expect(page.getByRole('heading', { name: '应用', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: '将博客从左侧菜单移除', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await showSidebar(page);
  const menu = page.getByRole('navigation', { name: '工作区', exact: true });
  await menu.getByRole('button', { name: '博客', exact: true }).click();
  await expect(page.locator('.blog-workspace')).toBeVisible();
  await expect(page).toHaveURL(/app=blog/);
  await showSidebar(page);
  await expect(page.getByRole('navigation', { name: '博客 主菜单', exact: true })).toBeVisible();
  await page.locator('.workspace-footer').getByRole('button', { name: '返回 DooKnow', exact: true }).click();
  await showSidebar(page);
  await menu.getByRole('button', { name: 'To Doo', exact: true }).click();
  await expect(page.locator('.to-doo-workspace')).toBeVisible();
  await expect(page).toHaveURL(/app=to-doo/);
  await page.goto('/?view=apps');
  await page.getByRole('button', { name: '将博客从左侧菜单移除', exact: true }).click();
  await page.reload();
  await showSidebar(page);
  await expect(menu.getByRole('button', { name: '博客', exact: true })).toHaveCount(0);
  await expect(menu.getByRole('button', { name: 'To Doo', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await closeSidebar(page);
});

test('opening a pinned app retains the mounted unsaved note', async ({ page, context }) => {
  await context.addCookies(JSON.parse(await readFile('.local/e2e-cookies.json', 'utf8')));
  await page.goto('/?view=apps');
  await page.getByRole('button', { name: '将博客加入左侧菜单', exact: true }).click();
  const original = '# 快捷应用\n\n原文保持不变。\n';
  const note = await openDocumentNote(page, context, original);
  await showSource(page);
  const editor = page.locator('.cm-content');
  await editor.fill('# 快捷应用\n\n切换应用后保留的草稿。\n');
  const handle = await editor.elementHandle();
  await showSidebar(page);
  const menu = page.getByRole('navigation', { name: '工作区', exact: true });
  await menu.getByRole('button', { name: '博客', exact: true }).click();
  await expect(page.locator('.blog-workspace')).toBeVisible();
  await showSidebar(page);
  await page.locator('.workspace-footer').getByRole('button', { name: '返回 DooKnow', exact: true }).click();
  await expect(editor).toContainText('切换应用后保留的草稿');
  expect(await handle!.evaluate(node => node.isConnected)).toBe(true);
  expect((await (await page.request.get('/api/notes/' + note.id)).json()).content).toBe(original);
  await handle?.dispose();
});

test('returning to the default menu respects the unsaved To Doo confirmation before opening a pinned app', async ({ page, context }) => {
  await context.addCookies(JSON.parse(await readFile('.local/e2e-cookies.json', 'utf8')));
  await page.goto('/?view=apps');
  await page.getByRole('button', { name: '将博客加入左侧菜单', exact: true }).click();
  await page.goto('/?view=apps&app=to-doo&appSection=settings');
  const zone = page.getByLabel('显示时区', { exact: true });
  await zone.fill('Etc/GMT+5');
  const originalURL = page.url();
  const menu = page.getByRole('navigation', { name: '工作区', exact: true });
  await showSidebar(page);
  await page.locator('.workspace-footer').getByRole('button', { name: '返回 DooKnow', exact: true }).click();
  await closeSidebar(page);
  const confirm = page.getByRole('dialog', { name: '尚有未保存内容', exact: true });
  await expect(confirm).toBeVisible();
  await confirm.getByRole('button', { name: '继续编辑', exact: true }).click();
  await expect(page).toHaveURL(originalURL);
  await expect(zone).toHaveValue('Etc/GMT+5');
  await showSidebar(page);
  await page.locator('.workspace-footer').getByRole('button', { name: '返回 DooKnow', exact: true }).click();
  await closeSidebar(page);
  await confirm.getByRole('button', { name: '放弃更改并离开', exact: true }).click();
  await showSidebar(page);
  await menu.getByRole('button', { name: '博客', exact: true }).click();
  await closeSidebar(page);
  await expect(page.locator('.blog-workspace')).toBeVisible();
  await expect(page).toHaveURL(/app=blog/);
});
