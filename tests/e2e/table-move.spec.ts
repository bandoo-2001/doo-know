import { test, expect } from '../support/browser-test';
import MarkdownIt from 'markdown-it';
import { openDocumentNote, saveDocument } from '../support/document-editor';

test('表格行列移动保留首行表头、列对齐和共享撤销', async ({ page, context }) => {
  const original = '前文\r\n\r\n| 左列 | 中列 | 右列 |\r\n| :--- | :---: | ---: |\r\n| 左一 | 中一 | 右一 |\r\n| 左二 | 中二 | 右二 |\r\n\r\n<!-- 原样保留 -->\r\n';
  const note = await openDocumentNote(page, context, original);
  const editor = page.getByRole('textbox', { name: '文档正文', exact: true });
  const tools = page.getByRole('toolbar', { name: '表格操作', exact: true });
  await editor.locator('th').filter({ hasText: '中列' }).click();
  await expect(tools.getByRole('button', { name: '上移行', exact: true })).toBeDisabled();
  await expect(tools.getByRole('button', { name: '下移行', exact: true })).toBeDisabled();
  await tools.getByRole('button', { name: '左移列', exact: true }).click();
  await expect(editor.locator('tr').first()).toHaveText('中列左列右列');
  await editor.locator('td').filter({ hasText: '中一' }).click();
  await expect(tools.getByRole('button', { name: '上移行', exact: true })).toBeDisabled();
  await expect(tools.getByRole('button', { name: '左移列', exact: true })).toBeDisabled();
  await tools.getByRole('button', { name: '下移行', exact: true }).click();
  await expect(editor.locator('tr').nth(1)).toHaveText('中二左二右二');
  await expect(editor.locator('tr').nth(2)).toHaveText('中一左一右一');
  await expect(tools.getByRole('button', { name: '下移行', exact: true })).toBeDisabled();
  await saveDocument(page);
  const saved = (await (await page.request.get('/api/notes/' + note.id)).json()).content;
  expect(saved.endsWith('<!-- 原样保留 -->\r\n')).toBe(true);
  const tokens = new MarkdownIt({ html: true }).parse(saved, {});
  expect(tokens.filter(token => token.type === 'th_open').map(token => token.attrGet('style'))).toEqual(['text-align:center', 'text-align:left', 'text-align:right']);
  await editor.locator(':scope > p').first().click();
  await page.keyboard.press('End');
  await page.keyboard.insertText('补充正文');
  await page.keyboard.press('ControlOrMeta+z');
  await expect(editor.locator(':scope > p').first()).toHaveText('前文');
  await expect(editor.locator('tr').nth(1)).toHaveText('中二左二右二');
  await page.keyboard.press('ControlOrMeta+z');
  await expect(editor.locator('tr').nth(1)).toHaveText('中一左一右一');
  await page.keyboard.press('ControlOrMeta+z');
  await expect(editor.locator('tr').first()).toHaveText('左列中列右列');
  await saveDocument(page);
  expect((await (await page.request.get('/api/notes/' + note.id)).json()).content).toBe(original);
});
